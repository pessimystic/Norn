CREATE TABLE book(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255)NOT NULL,
    author VARCHAR(255)NOT NULL,
    status VARCHAR(20)NOT NULL DEFAULT 'TBR',
    genre VARCHAR(100),
    rating INTEGER,
    review TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chck_book_status CHECK ( status IN('TBR','READING','FINISHED') ),
    CONSTRAINT chck_book_rating CHECK(rating IS NULL OR rating BETWEEN 1 AND 5)
    );